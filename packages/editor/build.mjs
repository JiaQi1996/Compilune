import { build } from "esbuild";
import { readFile, writeFile, mkdir, cp } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const editorRoot = path.dirname(fileURLToPath(import.meta.url));
const outputFlag = process.argv.indexOf("--outdir");
if (outputFlag !== -1 && !process.argv[outputFlag + 1])
  throw new Error("--outdir requires a path");
const resourceRoot =
  outputFlag === -1
    ? path.resolve(editorRoot, "../../apps/macos/Sources/Compilune/Resources")
    : path.resolve(process.argv[outputFlag + 1]);
await cp(
  path.join(editorRoot, "static/Editor"),
  path.join(resourceRoot, "Editor"),
  { recursive: true },
);
const result = await build({
  absWorkingDir: editorRoot,
  entryPoints: ["src.js"],
  bundle: true,
  format: "iife",
  outfile: path.join(resourceRoot, "Editor/editor.js"),
  minify: true,
  legalComments: "eof",
  metafile: true,
});
await build({
  absWorkingDir: editorRoot,
  entryPoints: ["bibliography-host.js"],
  bundle: true,
  format: "cjs",
  outfile: path.join(resourceRoot, "Bibliography.cjs"),
  target: "es2020",
});

await cp(path.join(editorRoot, "node_modules/katex/dist/katex.min.css"), path.join(resourceRoot, "Editor/katex.min.css"));
await cp(path.join(editorRoot, "node_modules/katex/dist/fonts"), path.join(resourceRoot, "Editor/fonts"), { recursive: true });

// Keep notices aligned with packages actually included in the editor bundle.
const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input
    .replaceAll("\\", "/")
    .match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
  if (match) packages.add(match[1]);
}
const licenseRoot = path.join(resourceRoot, "Licenses");
await mkdir(licenseRoot, { recursive: true });
const notices = [
  "# Bundled editor dependencies",
  "",
  "Generated by `npm --prefix packages/editor run build`.",
  "",
];
for (const name of [...packages].sort()) {
  const packageRoot = path.join(editorRoot, "node_modules", name);
  const info = JSON.parse(
    await readFile(path.join(packageRoot, "package.json"), "utf8"),
  );
  let license;
  for (const filename of [
    "LICENSE",
    "LICENSE.txt",
    "LICENSE.md",
    "LICENSE-MIT",
  ]) {
    try {
      license = await readFile(path.join(packageRoot, filename), "utf8");
      break;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  if (!license)
    throw new Error(`Missing license text for bundled package ${name}`);
  await writeFile(
    path.join(licenseRoot, `${name.replaceAll("/", "-")}.txt`),
    license,
  );
  notices.push(`- ${name} ${info.version} — ${info.license}`);
}
notices.push("", "Lucide icons: see `../Editor/LUCIDE-LICENSE.txt`.", "");
await writeFile(path.join(licenseRoot, "NOTICE.md"), notices.join("\n"));
console.log(
  `Built editor bundle and notices for ${packages.size} runtime dependencies.`,
);
